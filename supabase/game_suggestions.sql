create or replace function public.moderate_game_suggestion(
  p_suggestion_id bigint,
  p_action text,
  p_reason text default ''
)
returns text
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_status text;
begin
  if not public.is_site_admin() then raise exception 'Недостаточно прав.'; end if;

  v_status := case p_action
    when 'approve' then 'approved'
    when 'reject' then 'rejected'
    when 'select' then 'selected'
    when 'complete' then 'completed'
    when 'archive' then 'archived'
    when 'reopen' then 'approved'
    else null
  end;
  if v_status is null then raise exception 'Неизвестное действие модерации.'; end if;

  if v_status = 'selected' then
    update public.game_suggestions
       set status = 'approved', moderated_at = now(), moderated_by = auth.uid()
     where status = 'selected' and id <> p_suggestion_id;
  end if;

  update public.game_suggestions
     set status = v_status,
         rejection_reason = case when v_status = 'rejected' then left(btrim(coalesce(p_reason, '')), 500) else '' end,
         moderated_at = now(),
         moderated_by = auth.uid()
   where id = p_suggestion_id;
  if not found then raise exception 'Предложение не найдено.'; end if;
  return v_status;
end;
$$;

