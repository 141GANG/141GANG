create table if not exists public.game_suggestions (
  id bigint generated by default as identity primary key,
  steam_app_id bigint not null unique check (steam_app_id > 0),
  steam_url text not null check (char_length(steam_url) between 20 and 500),
  title text not null check (char_length(title) between 1 and 120),
  cover_url text not null default '' check (char_length(cover_url) <= 1000),
  description text not null default '' check (char_length(description) <= 2000),
  status text not null default 'pending'
    check (status in ('pending', 'approved', 'rejected', 'selected', 'completed', 'archived')),
  rejection_reason text not null default '' check (char_length(rejection_reason) <= 500),
  submitted_by uuid default auth.uid() references auth.users(id) on delete set null,
  moderated_by uuid references auth.users(id) on delete set null,
  moderated_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  release_date date,
  release_date_text text not null default '' check (char_length(release_date_text) <= 120),
  coming_soon boolean not null default false,
  is_coop boolean not null default false,
  coop_min_players integer check (coop_min_players is null or coop_min_players between 1 and 256),
  coop_max_players integer check (coop_max_players is null or coop_max_players between 1 and 256),
  players_min integer not null default 1 check (players_min between 1 and 256),
  players_max integer not null default 1 check (players_max between 1 and 256),
  player_count_source text not null default '' check (char_length(player_count_source) <= 120),
  steam_snapshot_synced_at timestamptz
);

